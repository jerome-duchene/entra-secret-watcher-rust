use std::fmt::Write;
use std::sync::Arc;

use anyhow::Result;
use async_trait::async_trait;
use tracing::debug;

use super::{NotificationChannel, html_escape};
use crate::config::EmailOptions;
use crate::graph::GraphClient;
use crate::models::{CredentialStatus, ScanResult};

/// Sends the report through the Graph API (`Mail.Send`), no SMTP needed.
pub struct EmailChannel {
    options: EmailOptions,
    graph: Arc<GraphClient>,
}

impl EmailChannel {
    pub fn new(options: EmailOptions, graph: Arc<GraphClient>) -> Self {
        Self { options, graph }
    }
}

#[async_trait]
impl NotificationChannel for EmailChannel {
    fn name(&self) -> &'static str {
        "Email (Graph API)"
    }

    fn is_enabled(&self) -> bool {
        self.options.enabled
    }

    async fn send(&self, result: &ScanResult) -> Result<()> {
        let recipients: Vec<String> =
            self.options.to.split(',').map(str::trim).filter(|r| !r.is_empty()).map(String::from).collect();

        self.graph
            .send_mail(
                &self.options.from,
                &format!(
                    "🔐 Entra ID Credential Report — {} ({} expiring)",
                    result.tenant_name,
                    result.credentials.len()
                ),
                &build_html(result),
                &recipients,
            )
            .await?;

        debug!("Email notification sent to {}", self.options.to);
        Ok(())
    }
}

pub(crate) fn build_html(result: &ScanResult) -> String {
    const CELL: &str = "padding: 8px; border: 1px solid #ddd;";
    let mut out = String::new();

    out.push_str(
        r#"<div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 700px; margin: 0 auto;">
    <h2 style="color: #1a1a1a; border-bottom: 2px solid #e74c3c; padding-bottom: 8px;">
        🔐 Entra ID Credential Report
    </h2>
"#,
    );

    let _ = write!(
        out,
        r#"    <p style="color: #555;">
        <strong>Tenant:</strong> {}<br/>
        <strong>Scanned:</strong> {} UTC<br/>
        <strong>Applications scanned:</strong> {}
    </p>
"#,
        html_escape(&result.tenant_name),
        result.scanned_at.format("%Y-%m-%d %H:%M"),
        result.total_applications_scanned
    );

    if result.expired_count() > 0 {
        let _ = write!(
            out,
            r#"    <div style="background: #fdecea; border-left: 4px solid #e74c3c; padding: 10px; margin: 10px 0;">
        ⚠️ <strong>{}</strong> credential(s) already expired!
    </div>
"#,
            result.expired_count()
        );
    }

    let _ = write!(
        out,
        r#"    <table style="width: 100%; border-collapse: collapse; margin-top: 15px;">
        <thead>
            <tr style="background: #f5f5f5;">
                <th style="padding: 8px; text-align: left; border: 1px solid #ddd;">Application</th>
                <th style="padding: 8px; text-align: left; border: 1px solid #ddd;">Type</th>
                <th style="padding: 8px; text-align: left; border: 1px solid #ddd;">Name</th>
                <th style="padding: 8px; text-align: left; border: 1px solid #ddd;">Status</th>
                <th style="padding: 8px; text-align: left; border: 1px solid #ddd;">Expires</th>
            </tr>
        </thead>
        <tbody>
"#
    );

    for credential in &result.credentials {
        let expired = credential.status() == CredentialStatus::Expired;
        let row_color = if expired { "#fdecea" } else { "#fff8e1" };
        let status_color = if expired { "#e74c3c" } else { "#f39c12" };

        let _ = write!(
            out,
            r#"            <tr style="background: {row_color};">
                <td style="{CELL}">{}</td>
                <td style="{CELL}">{}</td>
                <td style="{CELL}">{}</td>
                <td style="{CELL} color: {status_color}; font-weight: bold;">{}</td>
                <td style="{CELL}">{}</td>
            </tr>
"#,
            html_escape(&credential.app_name),
            credential.credential_type,
            html_escape(&credential.credential_name),
            credential.status_label(),
            credential.expires_on.format("%Y-%m-%d")
        );
    }

    out.push_str(
        r#"        </tbody>
    </table>
    <p style="color: #999; font-size: 12px; margin-top: 20px;">
        Generated by <strong>entra-secret-watcher</strong>
    </p>
</div>
"#,
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::EntraOptions;
    use crate::models::test_support::{credential, scan};
    use serde_json::{Value, json};
    use wiremock::matchers::{method, path};
    use wiremock::{Mock, MockServer, ResponseTemplate};

    #[test]
    fn html_contains_summary_and_rows() {
        let html = build_html(&scan(vec![credential(-2), credential(8)]));
        assert!(html.contains("<strong>Tenant:</strong> Contoso"));
        assert!(html.contains("2026-10-17 03:00 UTC"));
        assert!(html.contains("<strong>1</strong> credential(s) already expired!"));
        assert!(html.contains("EXPIRED since 2 day(s)"));
        assert!(html.contains("Expires in 8 day(s)"));
        assert!(html.contains("#fdecea")); // expired row
        assert!(html.contains("#fff8e1")); // expiring row
    }

    #[test]
    fn expired_banner_is_omitted_when_nothing_expired() {
        assert!(!build_html(&scan(vec![credential(8)])).contains("already expired"));
    }

    #[test]
    fn user_controlled_values_are_escaped() {
        let mut cred = credential(5);
        cred.app_name = "<script>alert(1)</script>".into();
        let html = build_html(&scan(vec![cred]));
        assert!(!html.contains("<script>"));
        assert!(html.contains("&lt;script&gt;"));
    }

    #[tokio::test]
    async fn sends_one_mail_to_all_recipients() {
        let server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/tenant/oauth2/v2.0/token"))
            .respond_with(ResponseTemplate::new(200).set_body_json(json!({ "access_token": "t", "expires_in": 3600 })))
            .mount(&server)
            .await;
        Mock::given(method("POST"))
            .and(path("/graph/users/from%40contoso.com/sendMail"))
            .respond_with(ResponseTemplate::new(202))
            .expect(1)
            .mount(&server)
            .await;

        let graph = Arc::new(GraphClient::with_base_urls(
            reqwest::Client::new(),
            EntraOptions {
                tenant_id: "tenant".into(),
                client_id: "c".into(),
                client_secret: "s".into(),
                tenant_name: "x".into(),
            },
            &format!("{}/graph", server.uri()),
            &server.uri(),
        ));
        let channel = EmailChannel::new(
            EmailOptions { enabled: true, from: "from@contoso.com".into(), to: " a@x.com, ,b@x.com ".into() },
            graph,
        );
        channel.send(&scan(vec![credential(3)])).await.unwrap();

        let requests = server.received_requests().await.unwrap();
        let mail = requests.iter().find(|r| r.url.path().ends_with("sendMail")).unwrap();
        let body: Value = serde_json::from_slice(&mail.body).unwrap();
        let recipients: Vec<_> = body["message"]["toRecipients"]
            .as_array()
            .unwrap()
            .iter()
            .map(|r| r["emailAddress"]["address"].as_str().unwrap())
            .collect();
        assert_eq!(recipients, ["a@x.com", "b@x.com"]);
        assert_eq!(body["message"]["subject"], "🔐 Entra ID Credential Report — Contoso (1 expiring)");
    }
}
